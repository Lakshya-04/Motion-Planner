#!/usr/bin/env python3
"""scenario_gen: write every consumer's inputs from one scenario.yaml. No ROS imports; the simulators are not edited.

    python3 -m scenario_sync.scenario_gen scenario.yaml OUT_DIR [--repo /path/to/Motion-Planner] [--no-sim-generators]

OUT_DIR gets
    plan/wall_scene.json         wall_scene.json for the coverage planner: the work patch (crop window or the full
                                 wall), world frame (frame_id = world_frame), obstacles kept
    plan/wall_scene_full.json    the whole wall, world frame (RViz, scorers)
    gazebo/wall_scene.json       the whole wall and its obstacles in the base-start frame (what the Gazebo sim builds)
    gazebo/wall.sdf              wall_world_gen's generator run on it with the scene frame kept (no re-centring),
                                 so launch it with `world:=`; the plane is `standoff_m - sim_wall_offset_m` ahead
    mujoco/wall_scene.json       the whole wall in the world frame
    mujoco/wall_world.xml        the wall geoms sim_mujoco's wall_world builds, placed with the inverse of the base
                                 start (`scene_offset`), inside <mujoco><worldbody>
    rviz_args.yaml               fixed frame, plan frame, wall_scene_json, base_x/y/yaw (+ mp_viz_scene parameters)
    env.sh                       shell snippet: launch arguments, MULTI_STAND_* variables, file paths
    manifest.json                every file and value written

The sim generators (src/simulation/sim_gazebo/sim_gazebo/wall_world.py and sim_mujoco/wall_world.py) are loaded from
the source tree by path (numpy only); without a source tree, or with --no-sim-generators, the SDF and MJCF are skipped.
"""
import argparse
import importlib.util
import json
import math
import os
import shlex
import sys

import numpy as np

from .geometry import (base_to_world, quat_from_matrix, vec_base_to_world, vec_world_to_base, world_to_base)
from .schema import ScenarioError, load_scenario

LEGACY_X = 0.98          # the plane the legacy multi-stand runners put the wall at (MULTI_STAND_WALL_DX shifts it)
LEGACY_MARGIN = 0.25     # sim wall margin the legacy runners leave around the patch


def find_repo(start=None):
    """The repository root (the directory with src/simulation/sim_gazebo), or None."""
    cands = [os.environ.get('SCENARIO_SYNC_REPO'), start, os.path.dirname(os.path.abspath(__file__))]
    for c in cands:
        d = os.path.abspath(c) if c else None
        while d and d != os.path.dirname(d):
            if os.path.isdir(os.path.join(d, 'src', 'simulation', 'sim_gazebo')):
                return d
            d = os.path.dirname(d)
    return None


def load_module(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    sys.modules[name] = mod
    spec.loader.exec_module(mod)
    return mod


def _r(x, n=6):
    return round(float(x) + 0.0, n)


# ------------------------------------------------------------------ wall_scene.json
def wall_scene(scn, window=None, frame_id=None, base_frame=False, with_obstacles=True):
    """A wall_scene.json dict. window=(u_range, v_range) crops the wall (origin and basis stay the wall's);
    base_frame=True expresses the wall in the base-start frame instead of the world frame."""
    f = scn.frame
    u, v, n = f.u, f.v, f.n
    o = f.point.copy()
    if base_frame:
        o = world_to_base(o, scn.base_pose)
        u, v, n = (vec_world_to_base(x, scn.base_pose) for x in (u, v, n))
    pu, pv = window if window else (scn.wall_u, scn.wall_v)
    d = -float(n @ o)
    wall = {'id': 0, 'plane_abcd': [_r(n[0]), _r(n[1]), _r(n[2]), _r(d)],
            'origin_xyz': [_r(x) for x in o], 'basis_u': [_r(x) for x in u], 'basis_v': [_r(x) for x in v],
            'normal_outward': [_r(x) for x in n], 'u_range_m': [_r(pu[0]), _r(pu[1])],
            'v_range_m': [_r(pv[0]), _r(pv[1])],
            'observed_area_m2': _r((pu[1] - pu[0]) * (pv[1] - pv[0]), 4), 'observed_fraction': 1.0}
    doc = {'frame_id': frame_id or scn.world_frame,
           'note': f'Generated by scenario_sync from scenario {scn.name!r}; do not edit, change scenario.yaml.',
           'units': 'meters', 'walls': [wall], 'obstacles': []}
    if with_obstacles:
        q = quat_from_matrix([u, v, n])
        for i, ob in enumerate(scn.obstacles):
            cu, cv = sum(ob['u']) / 2, sum(ob['v']) / 2
            w, h, depth = ob['u'][1] - ob['u'][0], ob['v'][1] - ob['v'][0], ob['depth']
            entry = {'id': i, 'parent_wall': 0, 'kind': ob['kind'], 'protrusion_min_m': depth,
                     'protrusion_max_m': depth, 'uv_on_wall': {'u': [_r(x) for x in ob['u']], 'v': [_r(x) for x in ob['v']]},
                     'inflation_m': 0.0}
            if ob['kind'] == 'box':
                c = o + u * cu + v * cv + n * depth / 2
                entry.update(box_center_xyz=[_r(x) for x in c], box_extents_uvn=[_r(w), _r(h), _r(depth)],
                             box_orientation_xyzw=[_r(x, 9) for x in q])
            doc['obstacles'].append(entry)
    return doc


def _write_json(path, doc):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w') as f:
        json.dump(doc, f, indent=2)
        f.write('\n')


# ------------------------------------------------------------------ simulator generators (by path)
def gazebo_sdf(repo, scene_path, out_path, standoff):
    wg = load_module(os.path.join(repo, 'src', 'simulation', 'sim_gazebo', 'sim_gazebo', 'wall_world.py'),
                     '_scenario_sync_gz_wall_world')
    # align=False keeps the scene frame (the scene is already in the base-start frame), so the wall is not re-centred
    return wg.generate_world(scene_path, out_path, wall_id=0, align=False, standoff=standoff)


def mujoco_world(repo, scene_path, out_path, offset):
    import xml.etree.ElementTree as ET
    mw = load_module(os.path.join(repo, 'src', 'simulation', 'sim_mujoco', 'sim_mujoco', 'wall_world.py'),
                     '_scenario_sync_mj_wall_world')
    geoms, prims, skipped = mw.wall_world_geoms(scene_path, offset=offset)
    root = ET.Element('mujoco', model='scenario_sync_wall_world')
    wb = ET.SubElement(root, 'worldbody')
    for g in geoms:
        wb.append(g)
    ET.indent(root)
    with open(out_path, 'w') as f:
        f.write(ET.tostring(root, encoding='unicode') + '\n')
    return len(geoms), skipped


# ------------------------------------------------------------------ legacy MULTI_STAND_* variables
def legacy_multi_stand(scn):
    """MULTI_STAND_* values of the runners (run_multi_stand_pass.sh) and why they cannot express the scenario, if so."""
    why = []
    f = scn.frame
    if not np.allclose(f.n, [-1.0, 0.0, 0.0], atol=1e-6):
        why.append('the runners put the wall at x = 0.98 facing -x')
    if not np.allclose(scn.base_pose, (0.0, 0.0, 0.0), atol=1e-6):
        why.append('the base starts at the origin')
    pu, pv = scn.patch_u, scn.patch_v
    y0, y1 = float(f.point[1] + pu[0]), float(f.point[1] + pu[1])
    z0, z1 = scn.patch_z
    dx = scn.standoff_m - LEGACY_X
    wy0, wy1 = float(f.point[1] + scn.wall_u[0]), float(f.point[1] + scn.wall_u[1])
    if abs(wy0 - (y0 - LEGACY_MARGIN)) > 1e-6 or abs(wy1 - (y1 + LEGACY_MARGIN)) > 1e-6:
        why.append(f'the runners build a sim wall with {LEGACY_MARGIN} m of margin around the patch (y {y0 - LEGACY_MARGIN:.2f}..'
                   f'{y1 + LEGACY_MARGIN:.2f}), the scenario wall is y {wy0:.2f}..{wy1:.2f}')
    if scn.obstacles:
        why.append('the runners add the obstacles of a named make_scenario_scene.py scenario only')
    vals = {'MULTI_STAND_WALL_DY': _r(y0), 'MULTI_STAND_WALL_WIDTH': _r(y1 - y0), 'MULTI_STAND_WALL_DX': _r(dx)}
    if abs(z0 - 1.0) > 1e-6 or abs(z1 - 1.3) > 1e-6:
        vals['MULTI_STAND_PATCH_Z'] = f'{_r(z0)},{_r(z1)}'
        why.append('MULTI_STAND_PATCH_Z needs MULTI_STAND_SCENARIO (a name from make_scenario_scene.py)')
    return vals, why


# ------------------------------------------------------------------ rviz / env
def rviz_args(scn, plan_json, full_json):
    fixed = scn.consumer('rviz').get('fixed_frame', scn.world_frame)
    f = scn.frame
    return {
        'scenario_sync': {
            'scenario': scn.name, 'fixed_frame': fixed, 'plan_frame': scn.world_frame,
            'wall_scene_json': plan_json, 'wall_scene_full_json': full_json,
            'base_x': _r(scn.base_x), 'base_y': _r(scn.base_y), 'base_yaw': _r(scn.base_yaw),
            'standoff_m': _r(scn.standoff_m),
        },
        # parameters of mp_viz_scene.py (src/common/mp_rviz, branch feat/rviz-profiles): the wall plane for PlanStands
        'mp_viz_scene': {'ros__parameters': {
            'frame_id': scn.world_frame, 'wall_point': [_r(x) for x in f.point],
            'wall_normal': [_r(x) for x in f.n]}},
    }


def env_sh(scn, out, files, mj_offset, legacy, why):
    q = shlex.quote
    off = float(scn.consumer('gazebo').get('sim_wall_offset_m', 0.0))
    L = [f'# scenario_sync env for scenario {scn.name!r}: source this file. Generated, do not edit.',
         f'export SCENARIO_NAME={q(scn.name)}',
         f'export SCENARIO_DIR={q(out)}',
         f'export SCENARIO_WORLD_FRAME={q(scn.world_frame)}',
         f'export SCENARIO_BASE_X={_r(scn.base_x)} SCENARIO_BASE_Y={_r(scn.base_y)} SCENARIO_BASE_YAW={_r(scn.base_yaw)}',
         f'export SCENARIO_STANDOFF_M={_r(scn.standoff_m)}',
         f'export SCENARIO_PROFILE={q(scn.robot_profile)} SCENARIO_TOOL_PROFILE={q(scn.tool_profile)}',
         f'export SCENARIO_LIFT_RANGE_M={q("%g %g" % tuple(scn.lift_range_m))}',
         '# coverage planner: wall_coverage_demo_node -p wall_scene_json:=$SCENARIO_PLAN_SCENE ... ; the plan stays in the world frame',
         f'export SCENARIO_PLAN_SCENE={q(files["plan_scene"])}',
         f'export SCENARIO_FULL_SCENE={q(files["full_scene"])}',
         f'export STAND_PROFILE={q(scn.robot_profile)} MP_PROFILE={q(scn.robot_profile)}',
         '# RViz: the file holds scenario_sync (fixed_frame, plan_frame, base_x/y/yaw, wall_scene_json) and mp_viz_scene parameters',
         f'export SCENARIO_RVIZ_ARGS={q(files["rviz_args"])}',
         f'export SCENARIO_RVIZ_FIXED_FRAME={q(scn.consumer("rviz").get("fixed_frame", scn.world_frame))}']
    if 'gazebo_sdf' in files:
        L += ['# Gazebo: the world generated from the scenario (wall at standoff - sim wall offset, not re-centred). The base',
              '# spawns at the sim origin, so the wall is placed relative to it. Use: ros2 launch sim_gazebo sim.launch.py "${SCENARIO_GAZEBO_LAUNCH_ARGS[@]}"',
              f'export SCENARIO_GAZEBO_WORLD={q(files["gazebo_sdf"])}',
              f'SCENARIO_GAZEBO_LAUNCH_ARGS=({q("world:=" + files["gazebo_sdf"])} {q("profile:=" + scn.robot_profile)})']
    L += [f'export SCENARIO_GAZEBO_WALL_SCENE={q(files["gazebo_scene"])}',
          '# or let the launch generate the world: it centres the wall on y = 0 and aligns it to the standoff, so a wall that is',
          '# not centred in front of the base is not reproduced (the generated wall.sdf above keeps the scene frame)',
          f'SCENARIO_GAZEBO_ALIGNED_ARGS=({q("wall_scene:=" + files["gazebo_scene"])} {q("standoff:=%s" % _r(scn.standoff_m - off))})',
          f'export SCENARIO_MUJOCO_WALL_SCENE={q(files["mujoco_scene"])}',
          '# MuJoCo: scene:= takes the world-frame scene, scene_offset:= carries it into the base-start frame.',
          '# Use: ros2 launch sim_mujoco sim_mujoco.launch.py "${SCENARIO_MUJOCO_LAUNCH_ARGS[@]}"',
          f'SCENARIO_MUJOCO_LAUNCH_ARGS=({q("profile:=" + scn.robot_profile)} {q("scene:=" + files["mujoco_scene"])} '
          f'{q("scene_offset:=" + " ".join(str(_r(x)) for x in mj_offset))})']
    L.append('# legacy run_multi_stand_pass.sh variables (the runners build their own wall from them)')
    for k, v in legacy.items():
        L.append(f'export {k}={q(str(v))}')
    for w in why:
        L.append(f'# WARNING: these variables do not reproduce the scenario: {w}')
    L.append('# check the result with: python3 -m scenario_sync.check_sync <scenario.yaml> --gen-dir "$SCENARIO_DIR" '
             '[--plan-output <run>/coverage_output.json]')
    return '\n'.join(L) + '\n'


def generate(scn, out, repo=None, sim_generators=True):
    """Write all artifacts to `out`; returns the manifest dict."""
    out = os.path.abspath(out)
    os.makedirs(out, exist_ok=True)
    files, notes = {}, list(scn.notes)
    window = None if scn.patch_mode == 'full' else (scn.patch_u, scn.patch_v)
    plan = wall_scene(scn, window=window)
    files['plan_scene'] = os.path.join(out, 'plan', 'wall_scene.json')
    _write_json(files['plan_scene'], plan)
    files['full_scene'] = os.path.join(out, 'plan', 'wall_scene_full.json')
    _write_json(files['full_scene'], wall_scene(scn))
    files['gazebo_scene'] = os.path.join(out, 'gazebo', 'wall_scene.json')
    _write_json(files['gazebo_scene'], wall_scene(scn, frame_id='odom', base_frame=True))
    files['mujoco_scene'] = os.path.join(out, 'mujoco', 'wall_scene.json')
    _write_json(files['mujoco_scene'], wall_scene(scn))

    off = float(scn.consumer('gazebo').get('sim_wall_offset_m', 0.0))
    # the sim wall of a consumer with a sim_wall_offset_m is moved along the normal toward the base by that much
    if off:
        gz = wall_scene(scn, frame_id='odom', base_frame=True)
        w = gz['walls'][0]
        n = np.array(w['normal_outward'])
        o = np.array(w['origin_xyz']) + n * off
        w['origin_xyz'] = [_r(x) for x in o]
        w['plane_abcd'][3] = _r(-float(n @ o))
        for ob in gz['obstacles']:
            if 'box_center_xyz' in ob:
                ob['box_center_xyz'] = [_r(x) for x in np.array(ob['box_center_xyz']) + n * off]
        _write_json(files['gazebo_scene'], gz)
        notes.append(f'gazebo/wall_scene.json is moved {off:.3f} m toward the base (sim_wall_offset_m)')

    base = scn.base_pose
    # scene_offset places a scene given in the world frame into the base frame: p_base = R(-yaw) (p_world - t)
    c, s = math.cos(-base[2]), math.sin(-base[2])
    t = np.array([base[0], base[1]])
    mj_offset = (_r(-(c * t[0] - s * t[1])), _r(-(s * t[0] + c * t[1])), 0.0, _r(-base[2]))

    repo = repo or find_repo()
    if sim_generators and repo:
        try:
            files['gazebo_sdf'] = os.path.join(out, 'gazebo', 'wall.sdf')
            gazebo_sdf(repo, files['gazebo_scene'], files['gazebo_sdf'], scn.standoff_m - off)
        except Exception as e:  # a generator that cannot run must not hide the other artifacts
            files.pop('gazebo_sdf', None)
            notes.append(f'gazebo/wall.sdf not written: {type(e).__name__}: {e}')
        try:
            files['mujoco_mjcf'] = os.path.join(out, 'mujoco', 'wall_world.xml')
            mujoco_world(repo, files['mujoco_scene'], files['mujoco_mjcf'], mj_offset)
        except Exception as e:
            files.pop('mujoco_mjcf', None)
            notes.append(f'mujoco/wall_world.xml not written: {type(e).__name__}: {e}')
    else:
        notes.append('simulator generators not run (no source tree found or --no-sim-generators)')

    files['rviz_args'] = os.path.join(out, 'rviz_args.yaml')
    import yaml
    ra = rviz_args(scn, files['plan_scene'], files['full_scene'])
    with open(files['rviz_args'], 'w') as f:
        f.write('# Generated by scenario_sync from scenario %r; do not edit.\n' % scn.name)
        yaml.safe_dump(ra, f, sort_keys=False)

    legacy, why = legacy_multi_stand(scn)
    files['env_sh'] = os.path.join(out, 'env.sh')
    with open(files['env_sh'], 'w') as f:
        f.write(env_sh(scn, out, files, mj_offset, legacy, why))
    manifest = {'scenario': scn.name, 'world_frame': scn.world_frame, 'files': files, 'notes': notes,
                'mujoco_scene_offset': list(mj_offset), 'gazebo_sim_wall_offset_m': off,
                'legacy_multi_stand': legacy, 'legacy_multi_stand_mismatch': why,
                'base_start': {'x': _r(scn.base_x), 'y': _r(scn.base_y), 'yaw': _r(scn.base_yaw)},
                'standoff_m': _r(scn.standoff_m), 'wall_area_m2': _r(scn.wall_area, 4),
                'patch_area_m2': _r(scn.patch_area, 4), 'patch_fraction_of_wall': _r(scn.patch_fraction, 4)}
    with open(os.path.join(out, 'manifest.json'), 'w') as f:
        json.dump(manifest, f, indent=2)
        f.write('\n')
    return manifest


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('scenario')
    ap.add_argument('out_dir')
    ap.add_argument('--repo', help='the Motion-Planner source tree (default: found from this file or SCENARIO_SYNC_REPO)')
    ap.add_argument('--no-sim-generators', action='store_true', help='do not run wall_world_gen / wall_world (no SDF, MJCF)')
    a = ap.parse_args(argv)
    try:
        scn = load_scenario(a.scenario)
    except (ScenarioError, OSError) as e:
        print(f'scenario_gen: {e}', file=sys.stderr)
        return 2
    m = generate(scn, a.out_dir, repo=a.repo, sim_generators=not a.no_sim_generators)
    print(f'scenario_gen: {scn.summary()}')
    for k, v in m['files'].items():
        print(f'  {k:14s} {v}')
    for n in m['notes']:
        print(f'  note: {n}')
    for w in m['legacy_multi_stand_mismatch']:
        print(f'  legacy MULTI_STAND_* do not reproduce the scenario: {w}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
